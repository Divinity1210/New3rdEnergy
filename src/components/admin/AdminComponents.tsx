export function DashboardCard({ title, value, change, icon, color }: {
  title: string;
  value: string | number;
  change?: number;
  icon: string;
  color?: string;
}) {
  return (
    <div className="admin-kpi-card" style={{ borderTopColor: color || 'var(--primary-600)' }}>
      <div className="admin-kpi-header">
        <span className="admin-kpi-icon">{icon}</span>
        <span className="admin-kpi-title">{title}</span>
      </div>
      <div className="admin-kpi-value">{typeof value === 'number' ? value.toLocaleString() : value}</div>
      {change !== undefined && change !== 0 && (
        <div className={cn('admin-kpi-change', change > 0 ? 'admin-kpi-positive' : 'admin-kpi-negative')}>
          {change > 0 ? '↑' : '↓'} {Math.abs(change).toFixed(1)}% vs prev period
        </div>
      )}
    </div>
  );
}

