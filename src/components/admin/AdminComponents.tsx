'use client';

import React from 'react';
import Link from 'next/link';
import { usePathname } from 'next/navigation';
import { UserRole } from '@/lib/types';
import { cn } from '@/lib/utils';

interface AdminSidebarProps {
  userRole: UserRole;
  userName: string;
  onLogout: () => void;
}

interface NavLink {
  label: string;
  href: string;
  icon: string;
  roles: UserRole[];
}

const navLinks: NavLink[] = [
  { label: 'Dashboard', href: '/admin', icon: '📊', roles: ['ADMIN', 'MARKETING', 'SALES', 'FINANCE', 'TECHNICAL', 'SUPPORT', 'READ_ONLY'] },
  { label: 'Leads', href: '/admin/leads', icon: '🎯', roles: ['ADMIN', 'SALES'] },
  { label: 'Pipeline', href: '/admin/pipeline', icon: '🔄', roles: ['ADMIN', 'SALES', 'MARKETING'] },
  { label: 'Contacts', href: '/admin/contacts', icon: '👥', roles: ['ADMIN', 'SALES', 'SUPPORT'] },
  { label: 'Automations', href: '/admin/automations', icon: '⚡', roles: ['ADMIN', 'SALES', 'MARKETING'] },
  { label: 'Knowledge Base', href: '/admin/knowledge', icon: '📚', roles: ['ADMIN', 'SUPPORT', 'TECHNICAL', 'SALES'] },
  { label: 'AI Insights', href: '/admin/insights', icon: '🧠', roles: ['ADMIN', 'MARKETING'] },
  { label: 'Audit Log', href: '/admin/audit', icon: '🔒', roles: ['ADMIN'] },
];

export function AdminSidebar({ userRole, userName, onLogout }: AdminSidebarProps) {
  const pathname = usePathname();
  const filteredLinks = navLinks.filter(link => link.roles.includes(userRole));

  return (
    <aside className="admin-sidebar">
      {/* Logo */}
      <div className="admin-sidebar-logo">
        <Link href="/admin" className="admin-logo-link">
          <span className="admin-logo-icon">⚡</span>
          <span className="admin-logo-text">3E Admin</span>
        </Link>
      </div>

      {/* Navigation */}
      <nav className="admin-sidebar-nav">
        {filteredLinks.map(link => (
          <Link
            key={link.href}
            href={link.href}
            className={cn(
              'admin-nav-link',
              (pathname === link.href || (link.href !== '/admin' && pathname?.startsWith(link.href))) && 'admin-nav-active'
            )}
          >
            <span className="admin-nav-icon">{link.icon}</span>
            <span className="admin-nav-label">{link.label}</span>
          </Link>
        ))}
      </nav>

      {/* User & Logout */}
      <div className="admin-sidebar-footer">
        <div className="admin-user-info">
          <div className="admin-user-avatar">{userName.charAt(0).toUpperCase()}</div>
          <div className="admin-user-details">
            <span className="admin-user-name">{userName}</span>
            <span className="admin-user-role">{userRole}</span>
          </div>
        </div>
        <button onClick={onLogout} className="admin-logout-btn">
          Sign Out
        </button>
        <Link href="/" className="admin-back-link">
          ← Back to Website
        </Link>
      </div>
    </aside>
  );
}

