export function AIInsightCard({ insight }: { insight: { type: string; title: string; description: string; confidence: number; sources: string[] } }) {
  const typeIcons: Record<string, string> = {
    trend: '📈',
    anomaly: '⚠️',
    opportunity: '💡',
    risk: '🔴',
  };

  return (
    <div className="admin-insight-card">
      <div className="admin-insight-header">
        <span className="admin-insight-icon">{typeIcons[insight.type] || '📊'}</span>
        <span className="admin-insight-title">{insight.title}</span>
        <span className="admin-insight-confidence">{Math.round(insight.confidence * 100)}% confidence</span>
      </div>
      <p className="admin-insight-desc">{insight.description}</p>
      <div className="admin-insight-sources">
        Sources: {insight.sources.join(', ')}
      </div>
    </div>
  );
}

